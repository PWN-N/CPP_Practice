#include <bits/stdc++.h>
using namespace std;

class solution{
public:
    int add(int a, int b) {
        int c = a+b;
        return c;
    }
    
    int subtract(int a, int b) {
        int d = a - b;
        return d;
        
    }
    
    int multiply(int a, int b) {
        int e = a * b;
        return e;
    }
    
    int divide(int a, int b) {
        int f = a/b;
        return f;
    }
};
